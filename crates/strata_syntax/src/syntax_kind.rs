impl SyntaxKind {
    /// Returns `true` if this kind represents whitespace or comments.
    #[inline]
    pub const fn is_trivia(self) -> bool {
        matches!(
            self,
            Self::Whitespace | Self::LineComment | Self::BlockComment
        )
    }

    /// Returns `true` if this kind is a token (non-composite leaf).
    #[inline]
    pub const fn is_token(self) -> bool {
        (self as u16) < (Self::SourceFile as u16)
    }
}

impl From<SyntaxKind> for rowan::SyntaxKind {
    #[inline]
    fn from(kind: SyntaxKind) -> Self {
        Self(kind as u16)
    }
}

/// `rowan::Language` marker type for Strata v2.0 CSTs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum StrataLanguage {}

impl rowan::Language for StrataLanguage {
    type Kind = SyntaxKind;

    #[inline]
    fn kind_from_raw(raw: rowan::SyntaxKind) -> Self::Kind {
        assert!(
            raw.0 < SyntaxKind::__Last as u16,
            "invalid raw SyntaxKind {}",
            raw.0
        );
        // Safe numeric match without transmute so `#![forbid(unsafe_code)]` holds.
        SYNTAX_KIND_TABLE[raw.0 as usize]
    }

    #[inline]
    fn kind_to_raw(kind: Self::Kind) -> rowan::SyntaxKind {
        rowan::SyntaxKind(kind as u16)
    }
}

/// Typed `rowan::SyntaxNode` alias for Strata v2.0.
