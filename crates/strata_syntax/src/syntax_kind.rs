#[cfg(test)]
mod tests {
    use super::*;
    use rowan::Language;

    /// Verifies `SYNTAX_KIND_TABLE` stays aligned 1-to-1 with every `SyntaxKind` discriminant.
    #[test]
    fn syntax_kind_table_matches_discriminants_one_to_one() {
        assert_eq!(SYNTAX_KIND_TABLE.len(), SyntaxKind::__Last as usize);
        for (idx, &expected) in SYNTAX_KIND_TABLE.iter().enumerate() {
            assert_eq!(expected as usize, idx, "table mismatch at index {idx}");
            let raw = StrataLanguage::kind_to_raw(expected);
            assert_eq!(raw.0 as usize, idx);
            assert_eq!(StrataLanguage::kind_from_raw(raw), expected);
        }
    }

    /// Verifies trivia predicate includes whitespace and both comment styles exclusively.
    #[test]
    fn trivia_classification_is_exact() {
        assert!(SyntaxKind::Whitespace.is_trivia());
        assert!(SyntaxKind::LineComment.is_trivia());
        assert!(SyntaxKind::BlockComment.is_trivia());
        assert!(!SyntaxKind::Ident.is_trivia());
        assert!(!SyntaxKind::Error.is_trivia());
        assert!(SyntaxKind::KwRpc.is_token());
        assert!(SyntaxKind::KwNetSimTest.is_token());
        assert!(!SyntaxKind::RpcDecl.is_token());
        assert!(!SyntaxKind::NetSimTestDecl.is_token());
        assert!(!SyntaxKind::NetSimParamList.is_token());
        assert!(!SyntaxKind::NetSimParam.is_token());
    }
}
