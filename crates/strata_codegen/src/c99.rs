//! Strict ISO C99 (`-std=c99 -Wall -Wextra -Wpedantic -Werror`) code generator targeting
//! `bamabi_sdk_gen::render_c99_header()` (`bamabi.h`, ABI `0.3.0`, 68 slots).

use crate::expr::{
    AssignOp, BinOpKind, BoundTerm, FieldRef, KernelExpr, KernelStmt, ScalarKind, SystemPlan,
    extract_system_plan,
};
use crate::{
    CodegenError, GeneratedArtifact, GeneratedFile, TargetKind, find_layout, is_ecs_component_kind,
    module_stem, sanitize_ident, system_schedule_label,
};
use bamabi_sys::{BAM_HOST_API_SLOT_COUNT, MAX_QUERIES_PER_SYSTEM, MAX_TERMS_PER_QUERY};
use core::fmt::Write as _;
use strata_mir::{MirFunction, MirModule};
use strata_sema::access::TermAccessMode;
use strata_sema::layout::{SchemaItemKind, SolvedField};
use strata_sema::types::Ty;

/// Emits strict ISO C99 (`<stem>.c` + `bamabi.h`) for `mir`.
pub fn emit(mir: &MirModule) -> Result<GeneratedArtifact, CodegenError> {
    let stem = module_stem(&mir.module_path);
    let mut c = String::with_capacity(8192);

    writeln!(
        c,
        "/* Auto-generated by strata_codegen (ISO C99 / bamabi ABI 0.3.0) */"
    )
    .ok();
    writeln!(c, "#include \"bamabi.h\"").ok();
    writeln!(c, "#include <stddef.h>").ok();
    writeln!(c, "#include <stdint.h>").ok();
    writeln!(c, "#include <string.h>\n").ok();

    writeln!(c, "/* Wire ABI truth guards derived from bamabi_sys */").ok();
    writeln!(
        c,
        "BAM_STATIC_ASSERT(BAM_HOST_API_SLOT_COUNT == {BAM_HOST_API_SLOT_COUNT}u, strata_abi_slot_count);"
    )
    .ok();
    writeln!(
        c,
        "BAM_STATIC_ASSERT(BAM_MAX_TERMS_PER_QUERY == {MAX_TERMS_PER_QUERY}u, strata_max_terms);"
    )
    .ok();
    writeln!(
        c,
        "BAM_STATIC_ASSERT(BAM_MAX_QUERIES_PER_SYSTEM == {MAX_QUERIES_PER_SYSTEM}u, strata_max_queries);\n"
    )
    .ok();

    // Emit explicit zero-padding C99 structs, layout assertions, UUIDs, fingerprints, and fields.
    emit_layouts(&mut c, mir);
    emit_rodata_tables_and_curves(&mut c, mir);

    // Emit per-World instance state holding resolved component & resource handles.
    let layout_count = mir.layouts.len().max(1);
    writeln!(c, "typedef struct StrataModState {{").ok();
    writeln!(c, "    const BamHostApi* api;").ok();
    writeln!(c, "    BamComponent components[{layout_count}];").ok();
    writeln!(c, "}} StrataModState;\n").ok();

    for func in &mir.functions {
        if func.is_observer {
            continue;
        }
        emit_system_fn(&mut c, mir, func);
    }

    emit_manifest_and_init(&mut c, mir, &stem);

    Ok(GeneratedArtifact {
        target: TargetKind::C99,
        module_name: mir.module_path.clone(),
        files: vec![
            GeneratedFile {
                path: "bamabi.h".to_owned(),
                content: crate::emit_bamabi_header(),
            },
            GeneratedFile {
                path: format!("{stem}.c"),
                content: c,
            },
        ],
    })
}

fn emit_layouts(out: &mut String, mir: &MirModule) {
    for (idx, layout) in mir.layouts.iter().enumerate() {
        let ident = sanitize_ident(&layout.canonical_name);
        if layout.size == 0 || layout.fields.is_empty() {
            writeln!(
                out,
                "typedef struct StrataType_{idx}_{ident} {{ uint8_t _zst_dummy; }} StrataType_{idx}_{ident};"
            )
            .ok();
        } else {
            writeln!(out, "typedef struct StrataType_{idx}_{ident} {{").ok();
            for field in &layout.fields {
                emit_c_field_decl(out, mir, field);
            }
            writeln!(out, "}} StrataType_{idx}_{ident};").ok();
            writeln!(
                out,
                "BAM_STATIC_ASSERT(sizeof(StrataType_{idx}_{ident}) == {size}u, strata_sz_{idx}_{ident});",
                size = layout.size
            )
            .ok();
            writeln!(
                out,
                "BAM_STATIC_ASSERT(BAM_ALIGNOF(StrataType_{idx}_{ident}) == {align}u, strata_al_{idx}_{ident});",
                align = layout.align
            )
            .ok();
            for field in &layout.fields {
                writeln!(
                    out,
                    "BAM_STATIC_ASSERT(offsetof(StrataType_{idx}_{ident}, {fname}) == {off}u, strata_off_{idx}_{ident}_{fname});",
                    fname = sanitize_c_field(&field.name),
                    off = field.offset
                )
                .ok();
            }
        }

        // UUID bytes & schema fingerprint (only emit static tables when referenced by components/resources)
        if is_ecs_component_kind(layout.item_kind) || layout.item_kind == SchemaItemKind::Resource {
            write!(
                out,
                "static const BamComponentUuid STRATA_UUID_{idx}_{ident} = {{ {{ "
            )
            .ok();
            for (bi, b) in layout.uuid_bytes.iter().enumerate() {
                if bi > 0 {
                    out.push_str(", ");
                }
                write!(out, "0x{b:02X}u").ok();
            }
            writeln!(out, " }} }};").ok();
            writeln!(
                out,
                "static const uint64_t STRATA_FP_{idx}_{ident} = 0x{fp:016X}ull;",
                fp = layout.schema_fingerprint
            )
            .ok();
        }

        if !layout.fields.is_empty()
            && (is_ecs_component_kind(layout.item_kind)
                || layout.item_kind == SchemaItemKind::Resource)
        {
            writeln!(
                out,
                "static const BamFieldDesc STRATA_FIELDS_{idx}_{ident}[] = {{"
            )
            .ok();
            for field in &layout.fields {
                let kind_macro = c_field_kind_const(field.bam_field_kind);
                writeln!(
                    out,
                    "    {{ (uint32_t)sizeof(BamFieldDesc), {kind_macro}, \
                     {{ (const uint8_t*)\"{name}\", {nlen}u }}, \
                     {{ (const uint8_t*)\"{tag}\", {tlen}u }}, \
                     {off}u, {sz}u, {al}u }},",
                    name = field.name,
                    nlen = field.name.len(),
                    tag = field.type_tag,
                    tlen = field.type_tag.len(),
                    off = field.offset,
                    sz = field.size,
                    al = field.align
                )
                .ok();
            }
            writeln!(out, "}};").ok();
        }
        if layout.item_kind != SchemaItemKind::Resource && !is_ecs_component_kind(layout.item_kind)
        {
            writeln!(
                out,
                "/* Keep metadata symbol referenced without unused-const warnings */"
            )
            .ok();
        }
        out.push('\n');
    }
}

fn c_aligned_blob(ident: &str, byte_size: usize, field_align: usize) -> String {
    let sz = byte_size.max(1);
    if field_align >= 8 && sz.is_multiple_of(8) {
        format!("uint64_t {ident}[{}]", sz / 8)
    } else if field_align >= 4 && sz.is_multiple_of(4) {
        format!("uint32_t {ident}[{}]", sz / 4)
    } else if field_align >= 2 && sz.is_multiple_of(2) {
        format!("uint16_t {ident}[{}]", sz / 2)
    } else {
        format!("uint8_t {ident}[{sz}]")
    }
}

fn emit_c_field_decl(out: &mut String, mir: &MirModule, field: &SolvedField) {
    let fname = sanitize_c_field(&field.name);
    if field.is_padding {
        writeln!(out, "    uint8_t {fname}[{n}];", n = field.size.max(1)).ok();
        return;
    }
    let decl = c_type_for_ty(&field.ty, &fname, field.size, field.align, mir);
    writeln!(out, "    {decl};").ok();
}

fn c_type_for_ty(
    ty: &Ty,
    ident: &str,
    byte_size: usize,
    field_align: usize,
    mir: &MirModule,
) -> String {
    match ty {
        Ty::U8 => format!("uint8_t {ident}"),
        Ty::I8 => format!("int8_t {ident}"),
        Ty::Bool => format!("BamBool {ident}"),
        Ty::U16 => format!("uint16_t {ident}"),
        Ty::I16 => format!("int16_t {ident}"),
        Ty::U32 | Ty::Sym | Ty::Rgba8 => format!("uint32_t {ident}"),
        Ty::I32 | Ty::Fix32 => format!("int32_t {ident}"),
        Ty::U64 | Ty::Ref(_) => format!("uint64_t {ident}"),
        Ty::I64 | Ty::Fix64 => format!("int64_t {ident}"),
        Ty::F32 | Ty::UnitScalar { .. } | Ty::GraceWindow => format!("float {ident}"),
        Ty::F64 => format!("double {ident}"),
        Ty::Vec2 => format!("float {ident}[2]"),
        Ty::Vec3 => format!("float {ident}[3]"),
        Ty::Vec3a | Ty::Vec4 | Ty::Quat | Ty::Rgba => format!("float {ident}[4]"),
        Ty::IVec2 => format!("int32_t {ident}[2]"),
        Ty::IVec3 => format!("int32_t {ident}[3]"),
        Ty::UVec2 => format!("uint32_t {ident}[2]"),
        Ty::Mat3 => format!("float {ident}[9]"),
        Ty::Mat4 => format!("float {ident}[16]"),
        Ty::Asset(_) => format!("BamAssetHandle {ident}"),
        Ty::Array { elem, len } => {
            let inner = c_type_for_ty(elem, ident, byte_size / (*len).max(1), field_align, mir);
            if inner.ends_with(']') {
                c_aligned_blob(ident, byte_size, field_align)
            } else {
                format!("{inner}[{n}]", n = (*len).max(1))
            }
        }
        Ty::BitSet(bits) => {
            let words = (*bits).div_ceil(32).max(1);
            format!("uint32_t {ident}[{words}]")
        }
        Ty::InlineStr(_) | Ty::InputBuffer { .. } | Ty::SmallVec { .. } | Ty::Tuple(_) => {
            c_aligned_blob(ident, byte_size, field_align)
        }
        Ty::Named(n) => {
            if let Some(en) = mir.layouts.iter().find(|l| {
                l.canonical_name == *n || l.canonical_name.rsplit("::").next() == Some(n.as_str())
            }) && en.item_kind == SchemaItemKind::Enum
            {
                return match en.size {
                    1 => format!("uint8_t {ident}"),
                    2 => format!("uint16_t {ident}"),
                    _ => format!("uint32_t {ident}"),
                };
            }
            c_aligned_blob(ident, byte_size, field_align)
        }
        _ => c_aligned_blob(ident, byte_size, field_align),
    }
}

fn c_field_kind_const(kind: u32) -> &'static str {
    match kind {
        1 => "BAM_FIELD_KIND_BOOL",
        2 => "BAM_FIELD_KIND_U8",
        3 => "BAM_FIELD_KIND_I8",
        4 => "BAM_FIELD_KIND_U16",
        5 => "BAM_FIELD_KIND_I16",
        6 => "BAM_FIELD_KIND_U32",
        7 => "BAM_FIELD_KIND_I32",
        8 => "BAM_FIELD_KIND_U64",
        9 => "BAM_FIELD_KIND_I64",
        10 => "BAM_FIELD_KIND_F32",
        11 => "BAM_FIELD_KIND_F64",
        12 => "BAM_FIELD_KIND_USIZE",
        13 => "BAM_FIELD_KIND_ISIZE",
        17 => "BAM_FIELD_KIND_NESTED",
        _ => "BAM_FIELD_KIND_UNKNOWN",
    }
}

fn sanitize_c_field(name: &str) -> String {
    let mut s = String::with_capacity(name.len());
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            s.push(ch);
        } else {
            s.push('_');
        }
    }
    if s.is_empty() || s.as_bytes()[0].is_ascii_digit() {
        format!("f_{s}")
    } else {
        s
    }
}

fn emit_rodata_tables_and_curves(out: &mut String, mir: &MirModule) {
    for curve in &mir.curves {
        if curve.points.is_empty() {
            continue;
        }
        let cname = sanitize_ident(&curve.name);
        writeln!(out, "static const float STRATA_CURVE_X_{cname}[] = {{").ok();
        write!(out, "    ").ok();
        for (i, (x, _)) in curve.points.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            write!(out, "{x:.6}f").ok();
        }
        writeln!(out, "\n}};").ok();
        writeln!(out, "static const float STRATA_CURVE_Y_{cname}[] = {{").ok();
        write!(out, "    ").ok();
        for (i, (_, y)) in curve.points.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            write!(out, "{y:.6}f").ok();
        }
        writeln!(out, "\n}};").ok();
        writeln!(
            out,
            "static float strata_eval_curve_{cname}(float x) {{\n\
             \x20   const size_t n = {len}u;\n\
             \x20   size_t i;\n\
             \x20   if (x <= STRATA_CURVE_X_{cname}[0]) {{ return STRATA_CURVE_Y_{cname}[0]; }}\n\
             \x20   for (i = 0u; i + 1u < n; ++i) {{\n\
             \x20       if (x <= STRATA_CURVE_X_{cname}[i + 1u]) {{\n\
             \x20           float t = (x - STRATA_CURVE_X_{cname}[i]) / (STRATA_CURVE_X_{cname}[i + 1u] - STRATA_CURVE_X_{cname}[i]);\n\
             \x20           return STRATA_CURVE_Y_{cname}[i] + t * (STRATA_CURVE_Y_{cname}[i + 1u] - STRATA_CURVE_Y_{cname}[i]);\n\
             \x20       }}\n\
             \x20   }}\n\
             \x20   return STRATA_CURVE_Y_{cname}[n - 1u];\n\
             }}\n",
            len = curve.points.len()
        )
        .ok();
        writeln!(out, "typedef float (*strata_curve_fn_{cname})(float);").ok();
    }
}

fn find_layout_index(mir: &MirModule, key: &str) -> Option<usize> {
    let short = key.split('.').next().unwrap_or(key);
    mir.layouts.iter().position(|l| {
        l.canonical_name == short
            || l.canonical_name.rsplit("::").next() == Some(short)
            || sanitize_ident(&l.canonical_name) == sanitize_ident(short)
    })
}

fn emit_system_fn(out: &mut String, mir: &MirModule, func: &MirFunction) {
    let fn_ident = sanitize_ident(&func.name);
    let plan = extract_system_plan(func, mir);

    writeln!(
        out,
        "static BamResult strata_sys_{fn_ident}(BamSystemCtx* sys_ctx, void* user_data) {{"
    )
    .ok();
    writeln!(
        out,
        "    const StrataModState* state = (const StrataModState*)user_data;"
    )
    .ok();
    writeln!(out, "    const BamHostApi* api = state->api;").ok();
    writeln!(out, "    (void)sys_ctx;").ok();
    writeln!(out, "    (void)api;").ok();

    if plan.row_stmts.is_empty() || plan.query0_terms.is_empty() {
        // Still reference any curve pointers cleanly if needed; emit clean no-op when unlowered.
        writeln!(out, "    return BAM_RESULT_OK;").ok();
        writeln!(out, "}}\n").ok();
        return;
    }

    // Bind resource pointers needed by uniforms / loop.
    for (ri, res) in plan.resources.iter().enumerate() {
        let Some(layout_idx) = find_layout_index(mir, &res.canonical_name) else {
            continue;
        };
        if res.mutable {
            writeln!(
                out,
                "    uint8_t* res_ptr_{ri} = api->sys_res_mut_ptr(sys_ctx, state->components[{layout_idx}u], NULL);"
            )
            .ok();
        } else {
            writeln!(
                out,
                "    const uint8_t* res_ptr_{ri} = api->sys_res_ptr(sys_ctx, state->components[{layout_idx}u], NULL);"
            )
            .ok();
        }
        writeln!(
            out,
            "    if (res_ptr_{ri} == NULL) {{ return BAM_RESULT_OK; }}"
        )
        .ok();
        writeln!(out, "    (void)res_ptr_{ri};").ok();
    }

    // Emit uniforms.
    for stmt in &plan.uniforms {
        emit_c_stmt(out, stmt, &plan, "    ", false);
    }

    // Obtain query 0 iterator and iterate chunks.
    writeln!(out, "    BamIter* iter = NULL;").ok();
    writeln!(
        out,
        "    BamResult qres = api->sys_query(sys_ctx, 0u, &iter);"
    )
    .ok();
    writeln!(
        out,
        "    if (qres != BAM_RESULT_OK || iter == NULL) {{ return qres; }}"
    )
    .ok();
    writeln!(out, "    size_t chunk_len = 0u;").ok();
    writeln!(
        out,
        "    while (api->iter_next_chunk(iter, &chunk_len) != BAM_FALSE) {{"
    )
    .ok();

    for term in &plan.query0_terms {
        emit_c_chunk_term_borrow(out, term);
    }

    if plan.has_selective_writes {
        writeln!(out, "        size_t dirty_start = 0u;").ok();
        writeln!(out, "        size_t dirty_len = 0u;").ok();
    }

    writeln!(
        out,
        "        for (size_t row = 0u; row < chunk_len; ++row) {{"
    )
    .ok();
    if plan.has_selective_writes {
        writeln!(out, "            BamBool row_dirty = BAM_FALSE;").ok();
    }
    for stmt in &plan.row_stmts {
        emit_c_stmt(out, stmt, &plan, "            ", plan.has_selective_writes);
    }
    if plan.has_selective_writes {
        writeln!(
            out,
            "            if (row_dirty != BAM_FALSE) {{\n\
             \x20               if (dirty_len == 0u) {{\n\
             \x20                   dirty_start = row;\n\
             \x20                   dirty_len = 1u;\n\
             \x20               }} else if (dirty_start + dirty_len == row) {{\n\
             \x20                   dirty_len += 1u;\n\
             \x20               }} else {{\n"
        )
        .ok();
        for term in plan.query0_terms.iter().filter(|t| t.is_selective) {
            writeln!(
                out,
                "                    api->iter_mark_changed_range(iter, {ti}u, dirty_start, dirty_len);",
                ti = term.term_idx
            )
            .ok();
        }
        writeln!(
            out,
            "                    dirty_start = row;\n\
             \x20                   dirty_len = 1u;\n\
             \x20               }}\n\
             \x20           }}"
        )
        .ok();
    }
    writeln!(out, "        }}").ok();

    if plan.has_selective_writes {
        writeln!(out, "        if (dirty_len > 0u) {{").ok();
        for term in plan.query0_terms.iter().filter(|t| t.is_selective) {
            writeln!(
                out,
                "            api->iter_mark_changed_range(iter, {ti}u, dirty_start, dirty_len);",
                ti = term.term_idx
            )
            .ok();
        }
        writeln!(out, "        }}").ok();
    }

    writeln!(out, "    }}").ok();
    writeln!(out, "    return BAM_RESULT_OK;").ok();
    writeln!(out, "}}\n").ok();
}

fn emit_c_chunk_term_borrow(out: &mut String, term: &BoundTerm) {
    let ti = term.term_idx;
    match term.mode {
        TermAccessMode::Read | TermAccessMode::OptionalRead => {
            writeln!(
                out,
                "        const uint8_t* BAM_RESTRICT col_{ti} = api->iter_column_readonly(iter, {ti}u);"
            )
            .ok();
            if term.mode == TermAccessMode::Read {
                writeln!(
                    out,
                    "        if (col_{ti} == NULL) {{ return BAM_RESULT_INVALID_COMPONENT; }}"
                )
                .ok();
            }
            writeln!(out, "        (void)col_{ti};").ok();
        }
        TermAccessMode::Write | TermAccessMode::OptionalWrite => {
            writeln!(
                out,
                "        uint8_t* BAM_RESTRICT col_{ti} = api->iter_column_mutable(iter, {ti}u);"
            )
            .ok();
            if term.mode == TermAccessMode::Write {
                writeln!(
                    out,
                    "        if (col_{ti} == NULL) {{ return BAM_RESULT_INVALID_COMPONENT; }}"
                )
                .ok();
            }
            writeln!(out, "        (void)col_{ti};").ok();
        }
        TermAccessMode::SelectiveWrite => {
            writeln!(
                out,
                "        uint8_t* BAM_RESTRICT col_{ti} = api->iter_column_mutable_untracked(iter, {ti}u);"
            )
            .ok();
            writeln!(
                out,
                "        if (col_{ti} == NULL) {{ return BAM_RESULT_INVALID_COMPONENT; }}"
            )
            .ok();
            writeln!(out, "        (void)col_{ti};").ok();
        }
        _ => {}
    }
}

fn c_scalar_type(kind: ScalarKind) -> &'static str {
    match kind {
        ScalarKind::F32 => "float",
        ScalarKind::F64 => "double",
        ScalarKind::I32 => "int32_t",
        ScalarKind::U32 => "uint32_t",
        ScalarKind::I64 => "int64_t",
        ScalarKind::U64 => "uint64_t",
        ScalarKind::Bool => "BamBool",
    }
}

fn emit_c_stmt(
    out: &mut String,
    stmt: &KernelStmt,
    plan: &SystemPlan,
    indent: &str,
    track_dirty: bool,
) {
    match stmt {
        KernelStmt::Let { name, expr, kind } => {
            let cty = c_scalar_type(*kind);
            let cname = sanitize_c_field(name);
            let rhs = format_c_expr(expr, plan);
            writeln!(out, "{indent}{cty} loc_{cname} = ({cty})({rhs});").ok();
            writeln!(out, "{indent}(void)loc_{cname};").ok();
        }
        KernelStmt::Assign { target, op, value } => {
            let rhs = format_c_expr(value, plan);
            let lhs = format_c_lvalue(target, plan);
            let op_s = match op {
                AssignOp::Set => "=",
                AssignOp::AddAssign => "+=",
                AssignOp::SubAssign => "-=",
                AssignOp::MulAssign => "*=",
                AssignOp::DivAssign => "/=",
            };
            writeln!(out, "{indent}({lhs}) {op_s} ({rhs});").ok();
            if track_dirty
                && matches!(
                    target,
                    FieldRef::ColumnField {
                        is_selective: true,
                        ..
                    }
                )
            {
                writeln!(out, "{indent}row_dirty = BAM_TRUE;").ok();
            }
        }
        KernelStmt::If {
            cond,
            then_stmts,
            else_stmts,
        } => {
            let c = format_c_expr(cond, plan);
            writeln!(out, "{indent}if ({c}) {{").ok();
            for s in then_stmts {
                emit_c_stmt(out, s, plan, &format!("{indent}    "), track_dirty);
            }
            if else_stmts.is_empty() {
                writeln!(out, "{indent}}}").ok();
            } else {
                writeln!(out, "{indent}}} else {{").ok();
                for s in else_stmts {
                    emit_c_stmt(out, s, plan, &format!("{indent}    "), track_dirty);
                }
                writeln!(out, "{indent}}}").ok();
            }
        }
    }
}

fn format_c_lvalue(fref: &FieldRef, plan: &SystemPlan) -> String {
    match fref {
        FieldRef::Local(n) => format!("loc_{}", sanitize_c_field(n)),
        FieldRef::ResourceField {
            resource_canonical,
            byte_offset,
            kind,
            ..
        } => {
            let ri = plan
                .resources
                .iter()
                .position(|r| r.canonical_name == *resource_canonical)
                .unwrap_or(0);
            let cty = c_scalar_type(*kind);
            format!("*({cty}*)(res_ptr_{ri} + {byte_offset}u)")
        }
        FieldRef::ColumnField {
            term_idx,
            elem_size,
            byte_offset,
            kind,
            ..
        } => {
            let cty = c_scalar_type(*kind);
            format!("*({cty}*)(col_{term_idx} + row * {elem_size}u + {byte_offset}u)")
        }
    }
}

fn format_c_expr(expr: &KernelExpr, plan: &SystemPlan) -> String {
    match expr {
        KernelExpr::FloatLit(v) => format!("((float)({v:?}))"),
        KernelExpr::IntLit(v) => format!("((int32_t)({v}))"),
        KernelExpr::BoolLit(b) => {
            if *b {
                "BAM_TRUE".to_owned()
            } else {
                "BAM_FALSE".to_owned()
            }
        }
        KernelExpr::Load(fref) => match fref {
            FieldRef::ResourceField {
                resource_canonical,
                byte_offset,
                kind,
                ..
            } => {
                let ri = plan
                    .resources
                    .iter()
                    .position(|r| r.canonical_name == *resource_canonical)
                    .unwrap_or(0);
                let cty = c_scalar_type(*kind);
                format!("*(const {cty}*)(res_ptr_{ri} + {byte_offset}u)")
            }
            FieldRef::ColumnField {
                term_idx,
                elem_size,
                byte_offset,
                kind,
                ..
            } => {
                let cty = c_scalar_type(*kind);
                format!("*(const {cty}*)(col_{term_idx} + row * {elem_size}u + {byte_offset}u)")
            }
            FieldRef::Local(n) => format!("loc_{}", sanitize_c_field(n)),
        },
        KernelExpr::Neg(inner) => format!("(-({}))", format_c_expr(inner, plan)),
        KernelExpr::Not(inner) => format!("(!({}))", format_c_expr(inner, plan)),
        KernelExpr::Binary { op, lhs, rhs } => {
            let sym = match op {
                BinOpKind::Add => "+",
                BinOpKind::Sub => "-",
                BinOpKind::Mul => "*",
                BinOpKind::Div => "/",
                BinOpKind::Rem => "%",
                BinOpKind::Lt => "<",
                BinOpKind::Le => "<=",
                BinOpKind::Gt => ">",
                BinOpKind::Ge => ">=",
                BinOpKind::Eq => "==",
                BinOpKind::Ne => "!=",
                BinOpKind::And => "&&",
                BinOpKind::Or => "||",
            };
            format!(
                "(({}) {sym} ({}))",
                format_c_expr(lhs, plan),
                format_c_expr(rhs, plan)
            )
        }
    }
}

fn emit_manifest_and_init(out: &mut String, mir: &MirModule, stem: &str) {
    // Emit static BamManifest
    writeln!(
        out,
        "static StrataModState g_strata_state;\n\
         static const BamManifest STRATA_MANIFEST = {{\n\
         \x20   (uint32_t)sizeof(BamManifest),\n\
         \x20   BAM_ABI_VERSION,\n\
         \x20   \"{stem}\",\n\
         \x20   \"0.3.0\",\n\
         \x20   0u,\n\
         \x20   0u,\n\
         \x20   NULL,\n\
         \x20   NULL\n\
         }};\n\n\
         BAM_EXPORT const BamManifest* bamabi_manifest(void) {{\n\
         \x20   return &STRATA_MANIFEST;\n\
         }}\n"
    )
    .ok();

    writeln!(
        out,
        "BAM_EXPORT BamResult bamabi_init(const BamHostApi* api, BamLoadCtx* load_ctx, BamInstance** instance_out) {{"
    )
    .ok();
    writeln!(
        out,
        "    const BamHostCtx* host_ctx = NULL;\n\
         \x20   BamResult res = BAM_RESULT_OK;\n\
         \x20   if (api == NULL || load_ctx == NULL) {{ return BAM_RESULT_NULL_POINTER; }}\n\
         \x20   memset(&g_strata_state, 0, sizeof(g_strata_state));\n\
         \x20   g_strata_state.api = api;\n\
         \x20   host_ctx = api->load_host_ctx(load_ctx);\n\
         \x20   (void)host_ctx;\n\
         \x20   if (instance_out != NULL) {{ *instance_out = (BamInstance*)&g_strata_state; }}\n"
    )
    .ok();
    for curve in &mir.curves {
        if !curve.points.is_empty() {
            let cname = sanitize_ident(&curve.name);
            writeln!(out, "    (void)strata_eval_curve_{cname};").ok();
        }
    }

    // Register / resolve all SolvedLayouts.
    for (idx, layout) in mir.layouts.iter().enumerate() {
        let ident = sanitize_ident(&layout.canonical_name);
        if is_ecs_component_kind(layout.item_kind) {
            writeln!(
                out,
                "    {{\n\
                 \x20       BamComponentDesc cdesc;\n\
                 \x20       memset(&cdesc, 0, sizeof(cdesc));\n\
                 \x20       cdesc.struct_size = (uint32_t)sizeof(BamComponentDesc);\n\
                 \x20       cdesc.flags = 0x{flags:08X}u;\n\
                 \x20       cdesc.name = \"{cname}\";\n\
                 \x20       cdesc.uuid = STRATA_UUID_{idx}_{ident};\n\
                 \x20       cdesc.size = {size}u;\n\
                 \x20       cdesc.align = {align}u;\n\
                 \x20       cdesc.schema_fingerprint = STRATA_FP_{idx}_{ident};",
                flags = layout.component_flags,
                cname = layout.canonical_name,
                size = layout.size,
                align = layout.align,
            )
            .ok();
            if !layout.fields.is_empty() {
                writeln!(
                    out,
                    "        cdesc.fields = STRATA_FIELDS_{idx}_{ident};\n\
                     \x20       cdesc.field_count = {n}u;",
                    n = layout.fields.len()
                )
                .ok();
            }
            writeln!(
                out,
                "        res = api->register_component(load_ctx, &cdesc, &g_strata_state.components[{idx}u]);\n\
                 \x20       if (res != BAM_RESULT_OK) {{ return res; }}\n\
                 \x20   }}"
            )
            .ok();
        } else if layout.item_kind == SchemaItemKind::Resource {
            writeln!(
                out,
                "    res = api->resolve_component(host_ctx, \"{cname}\", &STRATA_UUID_{idx}_{ident}, &g_strata_state.components[{idx}u]);\n\
                 \x20   if (res == BAM_RESULT_NOT_FOUND) {{\n\
                 \x20       BamComponentDesc rdesc;\n\
                 \x20       memset(&rdesc, 0, sizeof(rdesc));\n\
                 \x20       rdesc.struct_size = (uint32_t)sizeof(BamComponentDesc);\n\
                 \x20       rdesc.flags = 0u;\n\
                 \x20       rdesc.name = \"{cname}\";\n\
                 \x20       rdesc.uuid = STRATA_UUID_{idx}_{ident};\n\
                 \x20       rdesc.size = {size}u;\n\
                 \x20       rdesc.align = {align}u;\n\
                 \x20       rdesc.schema_fingerprint = STRATA_FP_{idx}_{ident};",
                cname = layout.canonical_name,
                size = layout.size,
                align = layout.align
            )
            .ok();
            if !layout.fields.is_empty() {
                writeln!(
                    out,
                    "        rdesc.fields = STRATA_FIELDS_{idx}_{ident};\n\
                     \x20       rdesc.field_count = {n}u;",
                    n = layout.fields.len()
                )
                .ok();
            }
            writeln!(
                out,
                "        res = api->register_component(load_ctx, &rdesc, &g_strata_state.components[{idx}u]);\n\
                 \x20   }}\n\
                 \x20   if (res != BAM_RESULT_OK) {{ return res; }}"
            )
            .ok();
        }
    }

    // Register systems.
    for func in &mir.functions {
        if func.is_observer {
            continue;
        }
        let fn_ident = sanitize_ident(&func.name);
        let plan = extract_system_plan(func, mir);
        let sched = match system_schedule_label(mir, &func.name) {
            "Startup" => "BAM_SCHEDULE_STARTUP",
            "PreUpdate" => "BAM_SCHEDULE_PRE_UPDATE",
            "PostUpdate" => "BAM_SCHEDULE_POST_UPDATE",
            "Last" => "BAM_SCHEDULE_LAST",
            "Update" => "BAM_SCHEDULE_UPDATE",
            _ => "BAM_SCHEDULE_FIXED_UPDATE",
        };
        if plan.row_stmts.is_empty() || plan.query0_terms.is_empty() {
            // Register empty query if this system isn't a dense kernel loop yet.
            writeln!(
                out,
                "    {{\n\
                 \x20       BamSystemDesc sdesc;\n\
                 \x20       memset(&sdesc, 0, sizeof(sdesc));\n\
                 \x20       sdesc.struct_size = (uint32_t)sizeof(BamSystemDesc);\n\
                 \x20       sdesc.name = \"{sname}\";\n\
                 \x20       sdesc.callback = strata_sys_{fn_ident};\n\
                 \x20       sdesc.user_data = &g_strata_state;\n\
                 \x20       sdesc.schedule = {sched};\n\
                 \x20       res = api->register_system(load_ctx, &sdesc);\n\
                 \x20       if (res != BAM_RESULT_OK) {{ return res; }}\n\
                 \x20   }}",
                sname = func.name
            )
            .ok();
            continue;
        }

        // Build query 0 (entity terms) + optional query 1 (resource terms so sys_res_ptr is authorized).
        let mut term_lines = Vec::new();
        for term in &plan.query0_terms {
            if let Some(lidx) = find_layout_index(mir, &term.component_canonical) {
                let amode = match term.mode {
                    TermAccessMode::Write | TermAccessMode::SelectiveWrite => "BAM_ACCESS_WRITE",
                    TermAccessMode::OptionalRead => "BAM_ACCESS_OPTIONAL_READ",
                    TermAccessMode::OptionalWrite => "BAM_ACCESS_OPTIONAL_WRITE",
                    TermAccessMode::With => "BAM_ACCESS_FILTER_ONLY",
                    TermAccessMode::Without => "BAM_ACCESS_WITHOUT",
                    TermAccessMode::Has => "BAM_ACCESS_HAS",
                    TermAccessMode::Allow => "BAM_ACCESS_ALLOW",
                    _ => "BAM_ACCESS_READ",
                };
                term_lines.push(format!(
                    "{{ g_strata_state.components[{lidx}u], {amode}, 0u, 0u, 0u }}"
                ));
            }
        }
        let mut res_term_lines = Vec::new();
        for r in &plan.resources {
            if let Some(lidx) = find_layout_index(mir, &r.canonical_name) {
                let rmode = if r.mutable {
                    "BAM_ACCESS_RESOURCE_WRITE"
                } else {
                    "BAM_ACCESS_RESOURCE_READ"
                };
                res_term_lines.push(format!(
                    "{{ g_strata_state.components[{lidx}u], {rmode}, 0u, 0u, 0u }}"
                ));
            }
        }
        if term_lines.is_empty() && res_term_lines.is_empty() {
            writeln!(
                out,
                "    {{\n\
                 \x20       BamSystemDesc sdesc;\n\
                 \x20       memset(&sdesc, 0, sizeof(sdesc));\n\
                 \x20       sdesc.struct_size = (uint32_t)sizeof(BamSystemDesc);\n\
                 \x20       sdesc.name = \"{sname}\";\n\
                 \x20       sdesc.callback = strata_sys_{fn_ident};\n\
                 \x20       sdesc.user_data = &g_strata_state;\n\
                 \x20       sdesc.schedule = {sched};\n\
                 \x20       res = api->register_system(load_ctx, &sdesc);\n\
                 \x20       if (res != BAM_RESULT_OK) {{ return res; }}\n\
                 \x20   }}",
                sname = func.name
            )
            .ok();
        } else {
            writeln!(out, "    {{").ok();
            writeln!(out, "        BamQueryDesc qdescs[2];").ok();
            writeln!(out, "        size_t qcount = 0u;").ok();
            writeln!(out, "        memset(qdescs, 0, sizeof(qdescs));").ok();
            let mut q0_decl = String::new();
            if !term_lines.is_empty() {
                let nterms = term_lines.len();
                writeln!(out, "        BamTermDesc qterms[{nterms}] = {{").ok();
                for (ti, tl) in term_lines.iter().enumerate() {
                    let comma = if ti + 1 < nterms { "," } else { "" };
                    writeln!(out, "            {tl}{comma}").ok();
                }
                writeln!(out, "        }};").ok();
                writeln!(
                    out,
                    "        qdescs[qcount].struct_size = (uint32_t)sizeof(BamQueryDesc);\n\
                     \x20       qdescs[qcount].terms = qterms;\n\
                     \x20       qdescs[qcount].term_count = {nterms}u;\n\
                     \x20       qcount += 1u;"
                )
                .ok();
            }
            if !res_term_lines.is_empty() {
                let nr = res_term_lines.len();
                writeln!(out, "        BamTermDesc rterms[{nr}] = {{").ok();
                for (ri, rl) in res_term_lines.iter().enumerate() {
                    let comma = if ri + 1 < nr { "," } else { "" };
                    writeln!(out, "            {rl}{comma}").ok();
                }
                writeln!(out, "        }};").ok();
                writeln!(
                    out,
                    "        qdescs[qcount].struct_size = (uint32_t)sizeof(BamQueryDesc);\n\
                     \x20       qdescs[qcount].terms = rterms;\n\
                     \x20       qdescs[qcount].term_count = {nr}u;\n\
                     \x20       qcount += 1u;"
                )
                .ok();
            }
            let _ = &mut q0_decl;
            writeln!(out, "        BamSystemDesc sdesc;").ok();
            writeln!(out, "        memset(&sdesc, 0, sizeof(sdesc));").ok();
            writeln!(
                out,
                "        sdesc.struct_size = (uint32_t)sizeof(BamSystemDesc);\n\
                 \x20       sdesc.name = \"{sname}\";\n\
                 \x20       sdesc.queries = qdescs;\n\
                 \x20       sdesc.query_count = qcount;\n\
                 \x20       sdesc.callback = strata_sys_{fn_ident};\n\
                 \x20       sdesc.user_data = &g_strata_state;\n\
                 \x20       sdesc.schedule = {sched};\n\
                 \x20       res = api->register_system(load_ctx, &sdesc);\n\
                 \x20       if (res != BAM_RESULT_OK) {{ return res; }}\n\
                 \x20   }}",
                sname = func.name
            )
            .ok();
        }
    }

    writeln!(out, "    return BAM_RESULT_OK;\n}}\n").ok();
    writeln!(
        out,
        "BAM_EXPORT void bamabi_shutdown(BamInstance* instance) {{\n\
         \x20   (void)instance;\n\
         }}\n"
    )
    .ok();

    let _ = find_layout;
}

#[cfg(test)]
mod tests {
    use super::emit;
    use crate::TargetKind;
    use bamabi_sys::{BAM_HOST_API_SLOT_COUNT, MAX_QUERIES_PER_SYSTEM, MAX_TERMS_PER_QUERY};
    use strata_mir::lower_to_mir;
    use strata_sema::analyze_source;

    /// Verifies ISO C99 output embeds dynamic wire ABI static assertions derived from `bamabi_sys`.
    #[test]
    fn c99_emission_includes_wire_static_asserts_and_header() {
        let src = "module c::t @version(1.0.0);\ncomponent C { v: f32 = 0.0 }\nsys s() { for e in query(c: &mut C) { e.c.v += 1.0; } }\n";
        let sema = analyze_source("t.strata", src);
        let mir = lower_to_mir(&sema);
        let art = emit(&mir).expect("emit c99");
        assert_eq!(art.target, TargetKind::C99);
        assert_eq!(art.files[0].path, "bamabi.h");
        let c_src = &art.files[1].content;
        assert!(c_src.contains(&format!(
            "BAM_HOST_API_SLOT_COUNT == {BAM_HOST_API_SLOT_COUNT}u"
        )));
        assert!(c_src.contains(&format!(
            "BAM_MAX_TERMS_PER_QUERY == {MAX_TERMS_PER_QUERY}u"
        )));
        assert!(c_src.contains(&format!(
            "BAM_MAX_QUERIES_PER_SYSTEM == {MAX_QUERIES_PER_SYSTEM}u"
        )));
    }
}
